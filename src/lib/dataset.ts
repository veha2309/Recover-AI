export const demoDataset = (seed = 2026): RecoveryCase[] =>
  baseCases.map((item, index) => ({
    ...item,
    id: `RC-${seed}-${String(index + 1).padStart(3, "0")}`,
  }));

export function generatedDataset(count: number, seed: number): RecoveryCase[] {
  return Array.from({ length: count }, (_, i) => {
    const source = baseCases[(i * 7 + seed) % baseCases.length];
    const factor = 70 + ((i * 19 + seed) % 61);
    return {
      ...source,
      flags: { ...source.flags },
      evidence: [...source.evidence],
      outcomes: { ...source.outcomes },
      id: `GEN-${seed}-${String(i + 1).padStart(3, "0")}`,
      customer: `Customer ${seed}-${i + 1}`,
      amountMinor: (
        (BigInt(source.amountMinor) * BigInt(factor)) /
        100n
      ).toString(),
    };
  });
}

